// Builds app-source/i18n.js: the app's text in every language, the region
// names in every language, and small Japanese / Korean fonts holding just
// the characters the app uses (Batocera may not have CJK fonts).
//   node gen-i18n.js <app-source dir>
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const APP = process.argv[2];
const TR = require('./translations');
const main = fs.readFileSync(path.join(APP, 'main.js'), 'utf8');
const regionBlock = main.slice(main.indexOf('const REGIONS = ['), main.indexOf('];', main.indexOf('const REGIONS = [')));
const CODES = [...regionBlock.matchAll(/\['([a-z]{2}-[a-z]{2})'/g)].map(m => m[1]);
if (CODES.length < 30) throw new Error('could not read the regions from main.js');

const KEYS = Object.keys(TR.en);
const LANGS = Object.keys(TR);
for (const l of LANGS) {
  for (const k of KEYS) if (!(k in TR[l])) throw new Error(`${l} is missing ${k}`);
  for (const k of Object.keys(TR[l])) if (!(k in TR.en)) throw new Error(`${l} has an unknown key ${k}`);
}

// "Country (language)" for each region, in each language
const regionNames = {};
for (const l of LANGS) {
  const country = new Intl.DisplayNames([l], { type: 'region' });
  const lang = new Intl.DisplayNames([l], { type: 'language' });
  regionNames[l] = CODES.map(c => {
    const [lc, cc] = c.split('-');
    return `${country.of(cc.toUpperCase())} (${lang.of(lc)})`;
  });
}

// fonts: just the characters used
function charsOf(l) {
  const all = Object.values(TR[l]).flat().join('') + regionNames[l].join('') + TR.ja._name + TR.ko._name;
  return [...new Set([...all].filter(ch => ch.codePointAt(0) > 0x2e7f))].join('');
}
const font = (index, chars) => execFileSync('python3', ['-I', '-c', `
import sys, io, base64
from fontTools.ttLib import TTCollection
from fontTools import subset
f = TTCollection('/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc').fonts[${index}]
s = subset.Subsetter(subset.Options(layout_features=['*'], notdef_outline=True, hinting=False))
s.populate(text=sys.argv[1]); s.subset(f)
f.flavor = 'woff'
b = io.BytesIO(); f.save(b)
sys.stdout.write(base64.b64encode(b.getvalue()).decode())
`, chars], { maxBuffer: 64 << 20 }).toString();
const jp = font(0, charsOf('ja') + TR.ja._name);
const kr = font(1, charsOf('ko') + TR.ko._name);

const out = `// Generated by tools/gen-i18n.js from tools/translations.js. Do not edit by hand.
'use strict';
const LANGS = ${JSON.stringify(LANGS.map(l => [l, TR[l]._name]))};
const STRINGS = ${JSON.stringify(Object.fromEntries(LANGS.map(l => [l, TR[l]])), null, 0)};
const REGION_CODES = ${JSON.stringify(CODES)};
const REGION_NAMES = ${JSON.stringify(regionNames)};
// small fonts with only the Japanese / Korean characters used above
const FONT_CSS = "@font-face{font-family:'XC JP';src:url(data:font/woff;base64,${jp}) format('woff')}" +
  "@font-face{font-family:'XC KR';src:url(data:font/woff;base64,${kr}) format('woff')}";
const FONT_STACK = "sans-serif,'XC JP','XC KR'";

function lang(code) { return STRINGS[code] ? code : 'en'; }

// a system locale (Batocera's system.language, e.g. de_DE, pt_BR, nb_NO) as
// one of the app's languages; English when there's no match
function fromLocale(loc) {
  const s = String(loc || '').split('.')[0].split('@')[0].replace('-', '_').toLowerCase();
  const [base, area] = s.split('_');
  if (base === 'pt') return area === 'pt' ? 'pt-PT' : 'pt-BR';
  if (base === 'nb' || base === 'nn' || base === 'no') return 'nb';
  return STRINGS[base] && base !== 'pt' ? base : 'en';
}

// "2 seconds" in each language's grammar
function secs(code, n) {
  const forms = STRINGS[lang(code)]._sec;
  const whole = Number.isInteger(n);
  let i;
  if (forms.length === 4) {                     // Polish, Czech, Slovak
    if (!whole) i = 3;
    else if (n === 1) i = 0;
    else if (code === 'pl') i = (n % 10 >= 2 && n % 10 <= 4 && !(n % 100 >= 12 && n % 100 <= 14)) ? 1 : 2;
    else i = n >= 2 && n <= 4 ? 1 : 2;
  } else if (code === 'fr') i = n < 2 ? 0 : 1;
  else i = n === 1 ? 0 : 1;
  return forms[i].replace('{n}', n.toLocaleString(lang(code)));
}

// a string with {name} filled in (values are used as given: may be HTML)
function t(code, key, vars) {
  const s = STRINGS[lang(code)];
  let v = key in s ? s[key] : STRINGS.en[key];
  if (vars) v = v.replace(/\\{(\\w+)\\}/g, (m, k) => (k in vars ? vars[k] : m));
  return v;
}

module.exports = { LANGS, STRINGS, REGION_CODES, REGION_NAMES, FONT_CSS, FONT_STACK, lang, fromLocale, secs, t };
`;
fs.writeFileSync(path.join(APP, 'i18n.js'), out);
console.log(`i18n.js: ${LANGS.length} languages, ${KEYS.length} strings each, ${CODES.length} regions; fonts ${Math.round(jp.length / 1024)} KB + ${Math.round(kr.length / 1024)} KB (base64)`);
